#!/usr/bin/env python3
"""Build the project status report from the artefacts in the repository.

The report summarises what actually exists on disk: the generated models, the
measured size of every exported mesh, the validation results, the reference
set and the test suite.  Nothing is claimed that is not read back from a file.
"""

from __future__ import annotations

import argparse
import json
import struct
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent.parent
DOC_DIR = PROJECT_ROOT / "src" / "documentation"
MODEL_DIR = PROJECT_ROOT / "src" / "models"
REF_DIR = PROJECT_ROOT / "src" / "references"
PREVIEW_DIR = PROJECT_ROOT / "src" / "previews"


def stl_size(path: Path) -> dict:
    with path.open("rb") as handle:
        header = handle.read(84)
        count = struct.unpack("<I", header[80:84])[0]
        data = handle.read(50 * count)
    xs, ys, zs = [], [], []
    for index in range(count):
        values = struct.unpack("<12f", data[index * 50 : index * 50 + 48])
        for offset in (3, 6, 9):
            xs.append(values[offset])
            ys.append(values[offset + 1])
            zs.append(values[offset + 2])
    if not xs:
        return {"triangles": 0, "size_mm": [0, 0, 0]}
    return {
        "triangles": count,
        "size_mm": [
            round(max(xs) - min(xs), 2),
            round(max(ys) - min(ys), 2),
            round(max(zs) - min(zs), 2),
        ],
    }


def run_tests() -> str:
    completed = subprocess.run(
        [sys.executable, "-m", "unittest", "discover", "-s", "tests"],
        cwd=str(PROJECT_ROOT), capture_output=True, text=True,
    )
    tail = (completed.stderr or completed.stdout).strip().splitlines()
    return tail[-1] if tail else "no output"


def git_info() -> dict:
    def call(*args: str) -> str:
        try:
            return subprocess.run(
                ["git", *args], cwd=str(PROJECT_ROOT), capture_output=True, text=True
            ).stdout.strip()
        except Exception:  # pragma: no cover
            return ""

    return {
        "branch": call("rev-parse", "--abbrev-ref", "HEAD"),
        "head": call("rev-parse", "--short", "HEAD"),
        "commits": call("log", "--oneline", "-20"),
        "status": call("status", "--porcelain"),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-tests", action="store_true")
    args = parser.parse_args(argv)

    lines = [
        "# Project Report — Brihadisvara Temple 3-D Model",
        "",
        f"Generated: {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
        "",
        "This report is generated by `src/scripts/build_report.py` from the files",
        "that are actually present in the repository. It contains no hand written",
        "claims about artefacts that do not exist.",
        "",
        "## 1. Source projects (Blender)",
        "",
        "| File | Size (bytes) |",
        "|---|---|",
    ]
    for path in sorted((MODEL_DIR / "blender").glob("*.blend")):
        lines.append(f"| `{path.relative_to(PROJECT_ROOT)}` | {path.stat().st_size} |")

    lines += ["", "## 2. Print meshes (STL)", "", "| File | Triangles | Size X x Y x Z (mm) |", "|---|---|---|"]
    stl_files = sorted((MODEL_DIR / "stl").glob("*.stl")) + sorted((MODEL_DIR / "stl" / "modules").glob("*.stl"))
    for path in stl_files:
        info = stl_size(path)
        size = " x ".join(f"{value:.1f}" for value in info["size_mm"])
        lines.append(f"| `{path.relative_to(PROJECT_ROOT)}` | {info['triangles']} | {size} |")

    lines += ["", "## 3. Engineering solids (FreeCAD / STEP)", "", "| File | Size (bytes) |", "|---|---|"]
    for path in sorted((MODEL_DIR / "step").glob("*.step")):
        lines.append(f"| `{path.relative_to(PROJECT_ROOT)}` | {path.stat().st_size} |")
    fcstd = MODEL_DIR / "freecad" / "brihadisvara_engineering.FCStd"
    if fcstd.exists():
        lines.append(f"| `{fcstd.relative_to(PROJECT_ROOT)}` | {fcstd.stat().st_size} |")

    lines += ["", "## 4. Previews", "", "| File | Size (bytes) |", "|---|---|"]
    for path in sorted(PREVIEW_DIR.glob("*.png")):
        lines.append(f"| `{path.relative_to(PROJECT_ROOT)}` | {path.stat().st_size} |")

    manifest_path = REF_DIR / "image_manifest.json"
    if manifest_path.exists():
        payload = json.loads(manifest_path.read_text(encoding="utf-8"))
        images = payload.get("images", [])
        lines += [
            "",
            "## 5. Reference images",
            "",
            f"* {len(images)} files recorded in `src/references/image_manifest.json`",
        ]
        statuses: dict[str, int] = {}
        for entry in images:
            statuses[entry.get("status", "unknown")] = statuses.get(entry.get("status", "unknown"), 0) + 1
        for status, count in sorted(statuses.items()):
            lines.append(f"* {status}: {count}")

    validation_path = DOC_DIR / "validation_results.json"
    if validation_path.exists():
        payload = json.loads(validation_path.read_text(encoding="utf-8"))
        lines += ["", "## 6. Mesh validation", "", "| Model | Status |", "|---|---|"]
        for report in payload.get("reports", []):
            lines.append(f"| `{report['name']}` | {report['status']} |")

    lines += ["", "## 7. Tests", ""]
    if args.no_tests:
        lines.append("_Test run skipped (--no-tests)._")
    else:
        lines.append(f"`python3 -m unittest discover -s tests` → {run_tests()}")

    info = git_info()
    lines += [
        "",
        "## 8. Git",
        "",
        f"* branch: `{info['branch']}`",
        f"* HEAD: `{info['head']}`",
        "",
        "```",
        info["commits"],
        "```",
        "",
    ]
    if info["status"]:
        lines += ["Uncommitted files:", "", "```", info["status"], "```", ""]
    else:
        lines += ["The working tree is clean.", ""]

    output = DOC_DIR / "project_report.md"
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"report written to {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
